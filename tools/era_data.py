"""Build tools/.era-api/era_data.lua for the harness from the Classic Era client tables (db2/*.csv).

Contents: spell names/ranks, item names, GlobalStrings, valid events, and per-class spell knowledge
(class skill-line spells, talent ranks, and spells taught after a talent such as Bloodthirst ranks 2-4).

With a wow-ui-source checkout (classic_era branch) as argument, simple FrameXML constants
(NAME = number | "string" | OTHER_NAME) are included too, resolved to their values.

Usage: python3 tools/era_data.py [wow-ui-source checkout]
"""
import csv
import os
import re
import sys

API = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".era-api")
DB = os.path.join(API, "db2")

# Class skill lines (Classic Era), from SkillLine (CategoryID 7) by class mask.  Engraving (2851, Season of
# Discovery runes) is left out on purpose.
CLASS_SKILL_LINES = {
    1: (26, 256, 257),            # Warrior: Arms, Fury, Protection
    2: (184, 267, 594),           # Paladin: Retribution, Protection, Holy
    3: (50, 51, 163, 261),        # Hunter: Beast Mastery, Survival, Marksmanship, Beast Training
    4: (38, 39, 40, 253),         # Rogue: Combat, Subtlety, Poisons, Assassination
    5: (56, 78, 613),             # Priest: Holy, Shadow Magic, Discipline
    7: (373, 374, 375),           # Shaman: Enhancement, Restoration, Elemental Combat
    8: (6, 8, 237),               # Mage: Frost, Fire, Arcane
    9: (354, 355, 593),           # Warlock: Demonology, Affliction, Destruction
    11: (134, 573, 574),          # Druid: Feral Combat, Restoration, Balance
}


def rows(name):
    with open(os.path.join(DB, name + ".csv"), encoding="utf-8") as fh:
        yield from csv.DictReader(fh)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


names = {int(r["ID"]): r["Name_lang"] for r in rows("SpellName")}
sub = {int(r["ID"]): r["NameSubtext_lang"] for r in rows("Spell")}
items = {int(r["ID"]): r["Display_lang"] for r in rows("ItemSparse")}
levels = {}
if os.path.exists(os.path.join(DB, "SpellLevels.csv")):
    for r in rows("SpellLevels"):
        if int(r["DifficultyID"] or 0) == 0:
            levels[int(r["SpellID"])] = int(r["BaseLevel"] or 0)
strings = {r["BaseTag"]: r["TagText_lang"] for r in rows("GlobalStrings")}
events = sorted(set(re.findall(r'"([A-Z][A-Z0-9_]+)"', open(os.path.join(API, "Events.lua"), encoding="utf-8").read())))

talent_rows = list(rows("Talent"))
sla = list(rows("SkillLineAbility"))

out = ["-- Generated by tools/era_data.py from the Classic Era client tables; do not edit.", "return {"]

out.append("spells = {")
for i in sorted(names):
    out.append(f"[{i}]={{{lua_str(names[i])},{lua_str(sub.get(i, ''))},{levels.get(i, 0)}}},")
out.append("},")

out.append("items = {")
for i in sorted(items):
    out.append(f"[{i}]={lua_str(items[i])},")
out.append("},")

# Equip location per item (GetItemInfo's 9th return), from Item.InventoryType.
INVTYPES = {1: "INVTYPE_HEAD", 2: "INVTYPE_NECK", 3: "INVTYPE_SHOULDER", 4: "INVTYPE_BODY", 5: "INVTYPE_CHEST",
            6: "INVTYPE_WAIST", 7: "INVTYPE_LEGS", 8: "INVTYPE_FEET", 9: "INVTYPE_WRIST", 10: "INVTYPE_HAND",
            11: "INVTYPE_FINGER", 12: "INVTYPE_TRINKET", 13: "INVTYPE_WEAPON", 14: "INVTYPE_SHIELD",
            15: "INVTYPE_RANGED", 16: "INVTYPE_CLOAK", 17: "INVTYPE_2HWEAPON", 18: "INVTYPE_BAG", 19: "INVTYPE_TABARD",
            20: "INVTYPE_ROBE", 21: "INVTYPE_WEAPONMAINHAND", 22: "INVTYPE_WEAPONOFFHAND", 23: "INVTYPE_HOLDABLE",
            24: "INVTYPE_AMMO", 25: "INVTYPE_THROWN", 26: "INVTYPE_RANGEDRIGHT", 28: "INVTYPE_RELIC"}
equip = {}
if os.path.exists(os.path.join(DB, "Item.csv")):
    for r in rows("Item"):
        t = INVTYPES.get(int(r["InventoryType"] or 0))
        if t and int(r["ID"]) in items:
            equip[int(r["ID"])] = t
out.append("equipLoc = {" + ",".join(f"[{i}]={lua_str(t)}" for i, t in sorted(equip.items())) + "},")

out.append("strings = {")
for k in sorted(strings):
    if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k):
        out.append(f"{k}={lua_str(strings[k])},")
out.append("},")

out.append("events = {" + ",".join(f"{e}=true" for e in events) + "},")

# CVar defaults: ["name"] = {"default", category, account, character, secure, help}
cvars = {}
cvar_path = os.path.join(API, "CVars.lua")
if os.path.exists(cvar_path):
    for m in re.finditer(r'\["([A-Za-z0-9_]+)"\]\s*=\s*\{"((?:[^"\\]|\\.)*)"', open(cvar_path, encoding="utf-8").read()):
        cvars.setdefault(m.group(1), m.group(2))
out.append("cvars = {" + ",".join(f"[{lua_str(k)}]={lua_str(v)}" for k, v in sorted(cvars.items())) + "},")

# Simple FrameXML constants, e.g. INVSLOT_TABARD = 19; INVSLOT_LAST_EQUIPPED = INVSLOT_TABARD;
constants = {}
if len(sys.argv) > 1:
    raw = {}
    assign = re.compile(r'^([A-Z][A-Z0-9_]+)\s*=\s*(-?\d+(?:\.\d+)?|"[^"\\]*"|[A-Z][A-Z0-9_]+)\s*;?\s*(?:--.*)?$')
    for root_dir, _, fnames in os.walk(sys.argv[1]):
        for f in fnames:
            if f.endswith(".lua"):
                for line in open(os.path.join(root_dir, f), encoding="utf-8", errors="replace"):
                    m = assign.match(line.rstrip("\n"))
                    if m and m.group(1) not in raw:
                        raw[m.group(1)] = m.group(2)

    def resolve(name, depth=0):
        v = raw.get(name)
        if v is None or depth > 10:
            return None
        if re.match(r"^-?\d", v) or v.startswith('"'):
            return v
        return resolve(v, depth + 1) if v in raw else None

    for name in raw:
        v = resolve(name)
        if v is not None:
            constants[name] = v
out.append("constants = {" + ",".join(f"{k}={v}" for k, v in sorted(constants.items())) + "},")

# Deprecated globals that alias an Enum value, e.g. COMBATLOG_OBJECT_REACTION_FRIENDLY = Enum.CombatLogObject.ReactionFriendly
enum_aliases = {}
if len(sys.argv) > 1:
    alias = re.compile(r"^\s*([A-Z][A-Z0-9_]+)\s*=\s*(Enum\.[A-Za-z0-9_.]+)\s*;?\s*$")
    for root_dir, _, fnames in os.walk(os.path.join(sys.argv[1], "Interface", "AddOns")):
        if "Blizzard_Deprecated" not in root_dir:
            continue
        for f in fnames:
            if f.endswith(".lua"):
                for line in open(os.path.join(root_dir, f), encoding="utf-8", errors="replace"):
                    m = alias.match(line.rstrip("\n"))
                    if m:
                        enum_aliases.setdefault(m.group(1), m.group(2))
out.append("enumAliases = {" + ",".join(f"{k}={lua_str(v)}" for k, v in sorted(enum_aliases.items())) + "},")

out.append("classes = {")
for class_id, lines in CLASS_SKILL_LINES.items():
    mask = 1 << (class_id - 1)
    talents = []
    talent_spells = set()
    for r in talent_rows:
        if int(r["ClassID"] or 0) != class_id:
            continue
        ranks = [int(r[f"SpellRank_{i}"] or 0) for i in range(9)]
        ranks = [x for x in ranks if x]
        if ranks:
            talents.append((int(r["TabID"]), ranks))
            talent_spells.update(ranks)

    older = {}
    class_spells = []
    for r in sla:
        if int(r["SkillLine"]) in lines and (int(r["ClassMask"] or 0) in (0,) or int(r["ClassMask"]) & mask):
            s = int(r["Spell"])
            class_spells.append(s)
            sup = int(r["SupercedesSpell"] or 0)
            if sup:
                older[s] = sup

    def root(s):
        while s in older:
            s = older[s]
        return s

    # Later ranks of a talent ability (Pyroblast 2-8, Bloodthirst 2-4, ...) are only known with that talent.
    # SupercedesSpell is often 0 on Era, so match by name as well as by rank chain.
    talent_by_name = {}
    for tab, ranks in talents:
        if len(ranks) == 1 and names.get(ranks[0]):
            talent_by_name[names[ranks[0]]] = ranks[0]
    talent_taught = {}
    for s in set(class_spells):
        if s in talent_spells:
            continue
        if root(s) in talent_spells:
            talent_taught[s] = root(s)
        elif names.get(s) in talent_by_name:
            talent_taught[s] = talent_by_name[names[s]]
    base = sorted(s for s in set(class_spells) if s not in talent_taught and s not in talent_spells)

    out.append(f"[{class_id}] = {{")
    out.append("base = {" + ",".join(map(str, base)) + "},")
    out.append("talentTaught = {" + ",".join(f"[{s}]={t}" for s, t in sorted(talent_taught.items())) + "},")
    out.append("talents = {")
    for tab, ranks in talents:
        out.append(f"{{tab={tab},ranks={{{','.join(map(str, ranks))}}}}},")
    out.append("},")
    out.append("},")
out.append("},")
out.append("}")

path = os.path.join(API, "era_data.lua")
with open(path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print(f"Wrote {path}: {len(names)} spells, {len(items)} items, {len(strings)} strings, {len(events)} events, {len(constants)} constants")
